/// Validasi akurat apakah titik koordinat berada di dalam polygon administratif Kabupaten
bool isPointInKolakaUtaraPolygon(double lat, double lon) {
  // Bounding box filter cepat
  if (lat < -3.76 || lat > -2.76 || lon < 120.85 || lon > 121.46) {
    return false;
  }
  bool inside = false;
  final n = kolakaUtaraBoundary.length;
  for (int i = 0, j = n - 1; i < n; j = i++) {
    final xi = kolakaUtaraBoundary[i].longitude;
    final yi = kolakaUtaraBoundary[i].latitude;
    final xj = kolakaUtaraBoundary[j].longitude;
    final yj = kolakaUtaraBoundary[j].latitude;
    final intersect = ((yi > lat) != (yj > lat)) &&
        (lon < (xj - xi) * (lat - yi) / (yj - yi) + xi);
    if (intersect) inside = !inside;
  }
  return inside;
}
